import { test, expect, type Page } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

async function example(page: Page, scenario = 'stale') {
  await page.goto('/#/evidence');
  await page.getByRole('combobox', { name: 'Start with a real question' }).selectOption(scenario);
  await page.getByRole('button', { name: 'Try local example', exact: true }).click();
  await page.getByRole('button', { name: 'Allow local evidence', exact: true }).click();
  await expect(page.locator('.finding-card')).toBeVisible();
}
async function axe(page: Page) {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(result.violations.map(item => ({ id: item.id, description: item.description,
    nodes: item.nodes.map(node => ({ target: node.target, summary: node.failureSummary })) }))).toEqual([]);
}
