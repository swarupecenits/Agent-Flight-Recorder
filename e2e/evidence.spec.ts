test('evidence review, read-only playback, manifest, reviewed correction/export and recovery work together', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await example(page);
  await expect(page.locator('.finding-card').getByText('Unverifiable', { exact: true })).toBeVisible();
  await expect(page.getByText('A fresh check is needed.', { exact: true })).toBeVisible();
  await axe(page);
  await page.screenshot({ path: testInfo.outputPath('evidence-paper-review.png'), fullPage: true });
  let writes = 0;
  const listener = (request: { method(): string }) => { if (request.method() === 'POST') writes++; };
  page.on('request', listener);
  await page.getByRole('button', { name: 'See the result', exact: false }).click();
  await expect(page.getByRole('tab', { name: 'Timeline', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('slider', { name: 'Timeline position' })).toHaveValue('3');
  await page.getByText('Inspect actual result', { exact: true }).click();
  await expect(page.locator('.evidence-inspector .json-block').filter({ hasText: '"passed": 3' })).toBeVisible();
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await page.getByRole('button', { name: 'Play timeline', exact: true }).click();
  await expect(page.getByRole('slider', { name: 'Timeline position' })).toHaveValue('5');
  await expect(page.getByRole('button', { name: 'Play timeline', exact: true })).toBeVisible();
  expect(writes).toBe(0);
  page.off('request', listener);
  await page.getByRole('tab', { name: 'Manifest', exact: true }).click();
  await expect(page.getByRole('row').filter({ hasText: 'Mock health observations only' })).toContainText('Not observed');
  await expect(page.getByRole('row').filter({ hasText: 'In-memory unit assertions' })).toContainText('linked steps');
  await axe(page);
  await page.getByRole('tab', { name: 'Review', exact: true }).click();
  await page.getByRole('button', { name: 'Draft a clearer claim', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Review a clearer claim' })).toContainText('does not establish');
  await page.getByRole('button', { name: 'Save reviewed draft', exact: true }).click();
  await page.getByRole('tab', { name: 'Handoff', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Reviewed claim correction', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Review handoff export', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Review this plaintext export' })).toContainText('Unverifiable');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download reviewed file', exact: true }).click();
  expect((await download).suggestedFilename()).toMatch(/\.md$/);
  await page.getByRole('tab', { name: 'Recovery', exact: true }).click();
  await page.getByRole('button', { name: 'Review recovery plan', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Actual restart boundary', exact: true })).toBeVisible();
  await expect(page.locator('.recovery-plan')).toContainText('Event 2');
  await expect(page.locator('.recovery-plan')).toContainText('0 external writes');
  const executed = page.waitForResponse(response => response.url().endsWith('/api/lens/recovery/execute'));
  await page.getByRole('button', { name: 'Approve this plan & create new run', exact: true }).click();
  const corrected = await (await executed).json();
  expect(corrected.assessment.counts.Supported).toBe(1);
  expect(corrected.comparison.linked).toBe(true);
  await page.getByRole('tab', { name: 'Compare', exact: true }).click();
  await expect(page.getByRole('row').filter({ hasText: 'The final change passes the unit tests.' })).toContainText('Unverifiable');
  await expect(page.getByRole('row').filter({ hasText: 'The final change passes the unit tests.' })).toContainText('Supported');
  await page.screenshot({ path: testInfo.outputPath('evidence-recovery-comparison.png'), fullPage: true });
  await page.locator('.lens-recording').filter({ hasText: 'The code changed after the test' }).click();
  await page.getByRole('tab', { name: 'Review', exact: true }).click();
  await expect(page.locator('.finding-card').getByText('Unverifiable', { exact: true })).toBeVisible();
  await page.getByRole('navigation', { name: 'Primary' }).getByRole('link', { name: 'Recordings', exact: true }).click();
  await page.getByRole('navigation', { name: 'Primary' }).getByRole('link', { name: 'Evidence Lens', exact: true }).click();
  await expect(page.locator('.lens-recording')).toHaveCount(2);
  expect(errors).toEqual([]);
});
