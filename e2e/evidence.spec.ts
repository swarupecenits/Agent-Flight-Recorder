test('external preview can be cancelled and a failed live request never looks like a successful demo', async ({ page }) => {
  await example(page);
  let modelRequests = 0;
  page.on('request', request => { if (request.url().endsWith('/api/lens/live-demo')) modelRequests++; });
  await page.getByRole('button', { name: 'Use live Azure', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Review the live Azure request' })).toContainText('synthetic');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  expect(modelRequests).toBe(0);
  await page.getByRole('button', { name: 'Use live Azure', exact: true }).click();
  await page.getByRole('button', { name: 'Approve & run live Azure', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('FOUNDRY_NOT_CONFIGURED');
  expect(modelRequests).toBe(1);
  await expect(page.locator('.lens-recording')).toHaveCount(1);
  await expect(page.locator('.finding-card')).toContainText('Unverifiable');
});
